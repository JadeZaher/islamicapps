/**
 * Render docs/review/ai-review.md from procedures.ts, the same data /method shows. `--check` fails on drift.
 * Run: npx tsx src/lib/review/generate-doc.ts [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { sourceByCode } from '../sources/registry';
import {
  AI_REVIEW_MEANING,
  METHOD_SECTIONS,
  REVIEW_KIND_LABEL,
  SPECIALISTS,
  STATUS_LABEL,
  type RuleProcedure,
  type Specialist,
} from './procedures';

const credits = (codes: readonly string[]) => codes.map((code) => `\`${code}\` ${sourceByCode(code as never).name}`).join('; ');

function renderProcedure(procedure: RuleProcedure): string {
  const lines = [
    `### ${procedure.title} {#${procedure.id}}`,
    '',
    `\`${procedure.id}\` version \`${procedure.version}\` · ${REVIEW_KIND_LABEL.rule} · ${STATUS_LABEL[procedure.status]}`,
    '',
    `**Rule.** ${procedure.rule}`,
    '',
    `**Evidence.** ${procedure.evidence.join('; ')}.`,
    '',
    procedure.measured
      ? `**Measured.** ${procedure.measured.summary} Sample: ${procedure.measured.sample} Where: \`${procedure.measured.where}\`.`
      : `**Measured.** No measured accuracy. ${procedure.unmeasured ?? ''}`.trim(),
    '',
    `**Known failure modes.** ${procedure.failureModes.join('; ')}.`,
    '',
    `**Reader sees.** “${procedure.readerLabel}”`,
  ];
  if (procedure.excluded?.length) lines.push('', `**Excluded.** ${procedure.excluded.join('; ')}.`);
  lines.push('', `**Credited.** ${credits(procedure.sources)}.`, '', `**Code.** ${procedure.code.map((file) => `\`${file}\``).join(', ')}.`);
  return lines.join('\n');
}

function renderSpecialist(specialist: Specialist): string {
  return [
    `### ${specialist.title} {#specialist-${specialist.id}}`,
    '',
    `\`${specialist.id}\` version \`${specialist.version}\` · ${REVIEW_KIND_LABEL.specialist} · ${STATUS_LABEL[specialist.status]}`,
    '',
    `**Question.** ${specialist.question}`,
    '',
    `**System prompt.** [\`${specialist.prompt}\`](../../${specialist.prompt}) (version and SHA-256 in \`reviews/ai/specialists.json\`).`,
    '',
    `**Packet.** ${specialist.packet.join('; ')}. Nothing about how the pipeline scored the claim.`,
    '',
    `**Recommended model.** \`${specialist.recommendedModel}\`: ${specialist.modelReason}${specialist.notThisModel.length ? ` Not: ${specialist.notThisModel.join('; ')}.` : ''}`,
    '',
    specialist.measured
      ? `**Measured agreement.** ${specialist.measured.summary} (${specialist.measured.sample}; \`${specialist.measured.where}\`).`
      : `**Measured agreement.** None yet. ${specialist.unmeasured ?? ''}`.trim(),
  ].join('\n');
}

export function renderAiReviewMarkdown(): string {
  const parts = [
    '---',
    'type: reference',
    'generated_from: src/lib/review/procedures.ts',
    '---',
    '',
    '<!-- Generated by src/lib/review/generate-doc.ts. Do not edit by hand. -->',
    '',
    '# AI review: what each label means',
    '',
    AI_REVIEW_MEANING,
    '',
    `There are two kinds, never blurred. **${REVIEW_KIND_LABEL.rule}**: deterministic code, recorded with the procedure id, version and code hash; no model. **${REVIEW_KIND_LABEL.specialist}**: a model working as a specialist reviewer from a saved system prompt, cut off from how the claim was produced, recorded with the model id, the prompt hash, the packet hash and UTC start and finish times. The public page is \`/method\`; each heading below is its anchor.`,
    '',
    'Where a procedure has no measured accuracy, this page says so.',
  ];
  for (const section of METHOD_SECTIONS) {
    parts.push('', `## ${section.title} {#${section.id}}`, '', section.intro);
    for (const procedure of section.procedures) parts.push('', renderProcedure(procedure));
    for (const id of section.specialistIds) parts.push('', renderSpecialist(SPECIALISTS.find((specialist) => specialist.id === id)!));
  }
  return `${parts.join('\n')}\n`;
}

if (require.main === module) {
  const target = path.resolve(__dirname, '..', '..', '..', 'docs', 'review', 'ai-review.md');
  const text = renderAiReviewMarkdown();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      /* missing counts as drift */
    }
    if (current !== text) {
      console.error('docs/review/ai-review.md is out of date: run npx tsx src/lib/review/generate-doc.ts');
      process.exitCode = 1;
    } else console.log('ok   docs/review/ai-review.md is current');
  } else {
    writeFileSync(target, text, 'utf8');
    console.log('wrote docs/review/ai-review.md');
  }
}
