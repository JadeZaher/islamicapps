"""Write cases.md from the hand verdict files."""
import csv, json, collections
from common_t1 import *
TR=triage()
rows=list(csv.DictReader(open(HERE/"sample_verdicts.tsv",encoding="utf-8"),delimiter="\t"))
o=[]
o.append("---\ntype: analysis\n---\n# Tranche 01: cases (generated by build_cases_t1.py from the hand verdict files)\n")
o.append("## 1. Wrong or undecided readings among the read eligible readings\n")
for r in rows:
    if r["reader"] in("W","CT"):
        o.append(f"- **{r['id'][4:]}** ({r['group']}, {r['work']}, {r['source']}) reader **{r['reader']}**, stored {r['stored']} {r['stored_kind']}: {r['quote']}")
o.append("\n## 2. Reader right and stored chain also right (both right)\n")
o.append(", ".join(r["id"][4:] for r in rows if r["class"]=="BOTHR"))
o.append("\n\n## 3. The 15 eligible readings «no chain by reading» (all read)\n")
for r in rows:
    if r["applies"]=="no_chain": o.append(f"- {r['id'][4:]} ({r['reader']}): {r['quote']}")
extra=[l for l in (HERE/"v_nochain.txt").read_text(encoding="utf-8").splitlines() if l.strip()]
ids_in=set(r["id"] for r in rows)
# the census rows are all in sample_verdicts.tsv already (v_nochain.txt is one of the inputs)
o.append("\n## 4. Disagreements: 40 random of the 133 valid-but-different reports (seed 20261401)\n")
o.append("| id | right | cause | secondary | fixable in | text |\n|---|---|---|---|---|---|")
for l in (HERE/"v_dis40.txt").read_text(encoding="utf-8").splitlines():
    if l.startswith("#") or not l.strip(): continue
    a=l.split("|"); o.append(f"| {a[0]} | {a[1]} | {a[2]} | {a[3]} | {a[4]} | {a[5] if len(a)>5 else ''} |")
o.append("\n## 5. The 35 agreed readings with `needs_ruling` (both readers), grouped by the question\n")
names={"P":"The Prophet speaks a one-sentence report with no transmitter","E":"A narrated encounter where the Imam (or the source) speaks, inside the narrator's story: is he the last link?","S":"Two sayings (or a second saying, act or isnad) in one report: which is the report?","F":"A first-person narrative with an unnamed speaker or implicit transmission","B":"The author or title of a cited book (and a rescript from an Imam)","T":"A source known only by a title («منادي النبي»)"}
g=collections.defaultdict(list)
for l in (HERE/"v_needs_ruling.txt").read_text(encoding="utf-8").splitlines():
    if l.startswith("#") or not l.strip(): continue
    i,k,n=l.split("|",2); g[k].append((i,n))
for k in "PESFBT":
    o.append(f"\n### {names[k]} ({len(g[k])})")
    for i,n in g[k]: o.append(f"- {i}: {n}")
(HERE/"cases.md").write_text("\n".join(o)+"\n",encoding="utf-8")
print("cases.md written",sum(len(v) for v in g.values()))
