"""Point the reader jobs of a tranche not yet read at prompt v3.4: `tranches/tranche-NN/jobs.json` -> `tranche-NN/jobs-v3_4.json` (a NEW file; the original is never touched).

    python -B -X utf8 v3_4/make_jobs_v3_4.py --tranche 07            (from chain-reader/; writes tranches/tranche-07/jobs-v3_4.json)
    python -B -X utf8 v3_4/make_jobs_v3_4.py --tranche 07 --check    (print only)
    python -B -X utf8 v3_4/make_jobs_v3_4.py --tranche 07 --out <file>

Only the prompt changes (path, version, sha256 in `prompt` and in every `instruction`; `input_chars` by the difference of the two prompts' lengths) and `prompt_note`; packets, output directories,
run files and expected files are identical (the prompt changed rules and examples only; the packet builder is untouched). The source is jobs.json whatever prompt it names (v3.1 as built);
a tranche that already has outputs is refused unless `--force` (it was read under another prompt: v3_4/README.md §which tranches). See v3_4/AGENTS.md §jobs.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
NEW_JSON = HERE / "prompt-v3_4.json"
PROMPT_FILE = re.compile(r"v3(?:_\d)?([\\/])prompt-v3(?:_\d)?\.md$")


def prompt_chars(path: str) -> int:
    """Letters of the prompt a jobs file names (its file on disk; the jobs were sized with it)."""
    local = Path(path)
    if not local.is_file():
        local = ROOT / Path(*PROMPT_FILE.search(path).group(0).replace("\\", "/").split("/"))
    return len(local.read_text(encoding="utf-8"))


def convert(jobs: dict, new: dict, old_chars: int, new_chars: int) -> dict:
    """The jobs object with the prompt swapped (path, version, hash) everywhere it is named; `input_chars` moves by the prompt-length difference."""
    old = jobs["prompt"]
    match = PROMPT_FILE.search(old["path"])
    assert match, f"unexpected prompt path {old['path']!r}"
    new_path = old["path"][: match.start()] + f"v3_4{match.group(1)}prompt-v3_4.md"
    swaps = [(old["path"], new_path), (f"version {old['version']}", f"version {new['version']}"), (old["sha256"], new["sha256"])]
    result = json.loads(json.dumps(jobs))
    result["prompt"] = {"path": new_path, "version": new["version"], "sha256": new["sha256"]}
    result["prompt_note"] = "prompt v3.4 (v3_4/prompt-v3_4.md, the owner's third-round rulings): generated by v3_4/make_jobs_v3_4.py from jobs.json; every other field is unchanged"
    for job in result["jobs"]:
        for before, after in swaps:
            job["instruction"] = job["instruction"].replace(before, after)
        job["input_chars"] = job["input_chars"] - old_chars + new_chars
        assert old["sha256"] not in job["instruction"] and new["sha256"] in job["instruction"] and new_path in job["instruction"], job["job_id"]
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tranche", required=True, help="two digits (07)")
    parser.add_argument("--out", help="output file; default tranches/tranche-NN/jobs-v3_4.json")
    parser.add_argument("--check", action="store_true", help="print the summary, write nothing")
    parser.add_argument("--force", action="store_true", help="write even though the tranche has reader outputs")
    args = parser.parse_args(argv)
    number = f"{int(args.tranche):02d}"
    tranche = ROOT / "tranches" / f"tranche-{number}"
    read = sum(1 for _ in (tranche / "outputs").glob("pass-*/*.json")) if (tranche / "outputs").is_dir() else 0
    if read and not args.force:
        parser.error(f"tranche {number} already has {read} reader outputs: it is being read under another prompt (v3_4/README.md); --force to write anyway")
    new = json.loads(NEW_JSON.read_text(encoding="utf-8"))
    jobs = json.loads((tranche / "jobs.json").read_text(encoding="utf-8"))
    converted = convert(jobs, new, prompt_chars(jobs["prompt"]["path"]), new["chars"])
    target = Path(args.out) if args.out else tranche / "jobs-v3_4.json"
    print(f"tranche {number}: {len(converted['jobs'])} jobs, prompt {jobs['prompt']['version']} -> {converted['prompt']['version']} {converted['prompt']['sha256'][:12]}, -> {target}" + (" (check only)" if args.check else ""))
    if not args.check:
        target.write_text(json.dumps(converted, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
