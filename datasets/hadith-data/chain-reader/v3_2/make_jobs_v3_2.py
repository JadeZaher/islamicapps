"""Point the reader jobs of a tranche at prompt v3.2: `tranches/tranche-NN/jobs.json` (prompt v3.1) -> `tranche-NN/jobs-v3_2.json` (a NEW file; the original is never touched).

    python -B -X utf8 v3_2/make_jobs_v3_2.py --tranche 02            (from chain-reader/; writes tranches/tranche-02/jobs-v3_2.json)
    python -B -X utf8 v3_2/make_jobs_v3_2.py --tranche all           (tranches 02-10; 01 was read under v3.1)
    python -B -X utf8 v3_2/make_jobs_v3_2.py --tranche 02 --out <file> [--check]

Only the prompt changes (path, version, sha256, and `input_chars` by the difference of the two prompts' lengths): packets, output directories, run files and expected file names are identical, so no packet is rebuilt.
`--check` prints what would change and writes nothing. The v3.2 prompt is a DRAFT (no model has run it): do not launch jobs-v3_2.json before the owner approves the prompt (v3_2/README.md section 6).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OLD_JSON, NEW_JSON = ROOT / "v3_1" / "prompt-v3_1.json", HERE / "prompt-v3_2.json"


def convert(jobs: dict, old: dict, new: dict, old_chars: int, new_chars: int) -> dict:
    """The jobs object with the prompt swapped: every occurrence of the old path, version and hash in `prompt` and in each `instruction`; `input_chars` moves by the prompt-length difference."""
    old_path = jobs["prompt"]["path"]
    new_path = old_path.replace("v3_1\\prompt-v3_1.md", "v3_2\\prompt-v3_2.md").replace("v3_1/prompt-v3_1.md", "v3_2/prompt-v3_2.md")
    assert new_path != old_path, f"unexpected prompt path {old_path!r}"
    assert jobs["prompt"]["sha256"] == old["sha256"] and jobs["prompt"]["version"] == old["version"], "jobs.json is not for prompt v3.1"
    swaps = [(old_path, new_path), (f"version {old['version']}", f"version {new['version']}"), (old["sha256"], new["sha256"])]

    def swap(text: str) -> str:
        for before, after in swaps:
            text = text.replace(before, after)
        return text
    result = json.loads(json.dumps(jobs))
    result["prompt"] = {"path": new_path, "version": new["version"], "sha256": new["sha256"]}
    result["prompt_note"] = "prompt v3.2 DRAFT (v3_2/prompt-v3_2.md): generated by v3_2/make_jobs_v3_2.py from jobs.json; every other field is unchanged"
    for job in result["jobs"]:
        job["instruction"] = swap(job["instruction"])
        job["input_chars"] = job["input_chars"] - old_chars + new_chars
        assert old["sha256"] not in job["instruction"] and "v3_1" not in job["instruction"], job["job_id"]
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--tranche", required=True, help="two digits (02) or all (02-10)")
    parser.add_argument("--out", help="output file (one tranche only); default tranches/tranche-NN/jobs-v3_2.json")
    parser.add_argument("--check", action="store_true", help="print the summary, write nothing")
    args = parser.parse_args(argv)
    old, new = json.loads(OLD_JSON.read_text(encoding="utf-8")), json.loads(NEW_JSON.read_text(encoding="utf-8"))
    old_chars, new_chars = old["chars"], new["chars"]
    numbers = [f"{n:02d}" for n in range(2, 11)] if args.tranche == "all" else [f"{int(args.tranche):02d}"]
    if args.out and len(numbers) != 1:
        parser.error("--out needs one tranche")
    for number in numbers:
        source = ROOT / "tranches" / f"tranche-{number}" / "jobs.json"
        jobs = json.loads(source.read_text(encoding="utf-8"))
        converted = convert(jobs, old, new, old_chars, new_chars)
        target = Path(args.out) if args.out else source.with_name("jobs-v3_2.json")
        print(f"tranche {number}: {len(converted['jobs'])} jobs, prompt {converted['prompt']['version']} {converted['prompt']['sha256'][:12]}, input_chars per job {-(old_chars - new_chars):+d}, -> {target}" + (" (check only)" if args.check else ""))
        if not args.check:
            target.write_text(json.dumps(converted, ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
