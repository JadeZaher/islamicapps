/**
 * Write reviews/ai/specialists.json: every specialist, its prompt version and SHA-256, and the models that have run it
 * (from reviews/ai/records). `--check` fails when the file is out of date.
 * Run: npx tsx reviews/ai/tools/build-specialist-registry.ts [--check]
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { SPECIALISTS } from '../../../src/lib/review/procedures';
import { REPOSITORY_ROOT } from './packet-common';
import { promptInfo } from './specialist-lib';

const REGISTRY_PATH = path.join(REPOSITORY_ROOT, 'reviews', 'ai', 'specialists.json');

interface Run {
  model_id: string;
  provider_runtime: string;
  prompt_sha256: string;
  batch: string;
  records: number;
  first_started_at: string;
  last_finished_at: string;
}

function runsFor(specialistId: string): Run[] {
  const directory = path.join(REPOSITORY_ROOT, 'reviews', 'ai', 'records', specialistId);
  if (!existsSync(directory)) return [];
  const runs = new Map<string, Run>();
  for (const file of readdirSync(directory).filter((name) => name.endsWith('.jsonl')).sort()) {
    for (const line of readFileSync(path.join(directory, file), 'utf8').split('\n').filter(Boolean)) {
      const record = JSON.parse(line) as Record<string, string>;
      const key = `${record.model_id}\u001f${record.prompt_sha256}\u001f${file}`;
      const run = runs.get(key) ?? {
        model_id: record.model_id,
        provider_runtime: record.provider_runtime,
        prompt_sha256: record.prompt_sha256,
        batch: file.replace(/\.jsonl$/, ''),
        records: 0,
        first_started_at: record.started_at,
        last_finished_at: record.finished_at,
      };
      run.records += 1;
      if (record.started_at < run.first_started_at) run.first_started_at = record.started_at;
      if (record.finished_at > run.last_finished_at) run.last_finished_at = record.finished_at;
      runs.set(key, run);
    }
  }
  return [...runs.values()];
}

export function buildRegistry() {
  return {
    format: 'shura-specialist-registry/1',
    note: 'Generated by reviews/ai/tools/build-specialist-registry.ts from src/lib/review/procedures.ts, the prompt files and reviews/ai/records. Do not edit by hand.',
    specialists: SPECIALISTS.map((specialist) => {
      const prompt = promptInfo(path.join(REPOSITORY_ROOT, specialist.prompt));
      if (prompt.specialist !== specialist.id) throw new Error(`${specialist.prompt} names specialist ${prompt.specialist}`);
      return {
        id: specialist.id,
        version: specialist.version,
        claim_kinds: specialist.claimKinds,
        status: specialist.status,
        prompt_path: specialist.prompt,
        prompt_version: prompt.version,
        prompt_sha256: prompt.sha256,
        recommended_model: specialist.recommendedModel,
        not_this_model: specialist.notThisModel,
        runs: runsFor(specialist.id),
      };
    }),
  };
}

if (require.main === module) {
  const text = `${JSON.stringify(buildRegistry(), null, 2)}\n`;
  if (process.argv.includes('--check')) {
    const current = existsSync(REGISTRY_PATH) ? readFileSync(REGISTRY_PATH, 'utf8') : '';
    if (current !== text) {
      console.error('reviews/ai/specialists.json is out of date: run npx tsx reviews/ai/tools/build-specialist-registry.ts');
      process.exitCode = 1;
    } else console.log('ok   reviews/ai/specialists.json is current');
  } else {
    writeFileSync(REGISTRY_PATH, text, 'utf8');
    console.log('wrote reviews/ai/specialists.json');
  }
}
